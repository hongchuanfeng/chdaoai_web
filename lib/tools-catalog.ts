export const getToolBySlug = (slug: string): Tool | undefined => {
  return tools.find(t => t.slug === slug)
}

export const getToolsByCategory = (category: ToolCategory): Tool[] => {
  return tools.filter(t => t.category === category)
}

export const getRelatedTools = (slug: string, limit: number = 6): Tool[] => {
  const current = getToolBySlug(slug)
  if (!current) return []
  return tools
    .filter(t => t.slug !== slug && t.category === current.category)
    .slice(0, limit)
}

export const getPopularTools = (limit: number = 8): Tool[] => {
  return tools.filter(t => t.popular).slice(0, limit)
}

export const getAITools = (limit?: number): Tool[] => {
  const aiTools = tools.filter(t => t.isAI)
  return limit ? aiTools.slice(0, limit) : aiTools
}
