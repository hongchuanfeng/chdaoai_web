export type ToolCategory =
  | 'image'
  | 'video'
  | 'audio'
  | 'subtitle'
  | 'pdf'
  | 'csv'
  | 'ebook'
  | 'qrcode'
  | 'barcode'

export interface Tool {
  slug: string
  category: ToolCategory
  // i18n title/description
  title: { en: string; zh: string; es: string; fr: string; de: string; ja: string; ko: string; pt: string; ru: string; ar: string }
  shortDescription: { en: string; zh: string; es: string; fr: string; de: string; ja: string; ko: string; pt: string; ru: string; ar: string }
  longDescription: { en: string; zh: string; es: string; fr: string; de: string; ja: string; ko: string; pt: string; ru: string; ar: string }
  features: { en: string[]; zh: string[]; es: string[]; fr: string[]; de: string[]; ja: string[]; ko: string[]; pt: string[]; ru: string[]; ar: string[] }
  useCases: { en: string[]; zh: string[]; es: string[]; fr: string[]; de: string[]; ja: string[]; ko: string[]; pt: string[]; ru: string[]; ar: string[] }
  keywords: { en: string[]; zh: string[]; es: string[]; fr: string[]; de: string[]; ja: string[]; ko: string[]; pt: string[]; ru: string[]; ar: string[] }
  popular?: boolean
  isAI?: boolean
  isNew?: boolean
}

const en = (s: string) => ({ en: s, zh: s, es: s, fr: s, de: s, ja: s, ko: s, pt: s, ru: s, ar: s })

// Helper to construct a tool entry with en values, providing zh as fallback
const tool = (t: Omit<Tool, 'title' | 'shortDescription' | 'longDescription' | 'features' | 'useCases' | 'keywords'> & {
  titleEn: string; titleZh: string
  shortEn: string; shortZh: string
  longEn: string; longZh: string
  featuresEn: string[]; featuresZh: string[]
  useCasesEn: string[]; useCasesZh: string[]
  keywordsEn: string[]; keywordsZh: string[]
}): Tool => {
  // For non-en/non-zh languages, use the English text as a graceful fallback.
  // This is acceptable for AdSense because Google will see a real, translatable
  // page that simply hasn't been translated yet. The page itself remains valid
  // and high-quality for the languages we DO support.
  const wrap = (enText: string, zhText: string) => ({
    en: enText,
    zh: zhText,
    es: enText, fr: enText, de: enText, ja: enText, ko: enText, pt: enText, ru: enText, ar: enText,
  })
  const wrapArr = (enArr: string[], zhArr: string[]) => ({
    en: enArr,
    zh: zhArr,
    es: enArr, fr: enArr, de: enArr, ja: enArr, ko: enArr, pt: enArr, ru: enArr, ar: enArr,
  })
  return {
    slug: t.slug,
    category: t.category,
    popular: t.popular,
    isAI: t.isAI,
    isNew: t.isNew,
    title: wrap(t.titleEn, t.titleZh),
    shortDescription: wrap(t.shortEn, t.shortZh),
    longDescription: wrap(t.longEn, t.longZh),
    features: wrapArr(t.featuresEn, t.featuresZh),
    useCases: wrapArr(t.useCasesEn, t.useCasesZh),
    keywords: wrapArr(t.keywordsEn, t.keywordsZh),
  }
}

